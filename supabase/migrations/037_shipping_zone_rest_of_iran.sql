INSERT INTO public.shipping_zone_locations (zone_id, province, city)
SELECT z.id, p.province, NULL
FROM public.shipping_zones z
CROSS JOIN (VALUES
  ('آذربایجان شرقی'),
  ('آذربایجان غربی'),
  ('اردبیل'),
  ('اصفهان'),
  ('ایلام'),
  ('بوشهر'),
  ('چهارمحال و بختیاری'),
  ('خراسان جنوبی'),
  ('خراسان رضوی'),
  ('خراسان شمالی'),
  ('خوزستان'),
  ('زنجان'),
  ('سیستان و بلوچستان'),
  ('فارس'),
  ('قزوین'),
  ('کردستان'),
  ('کرمان'),
  ('کرمانشاه'),
  ('کهگیلویه و بویراحمد'),
  ('گلستان'),
  ('لرستان'),
  ('هرمزگان'),
  ('همدان'),
  ('یزد')
) AS p(province)
WHERE z.name = 'سایر ایران'
ON CONFLICT DO NOTHING;
